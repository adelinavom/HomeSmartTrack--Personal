    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        //delete appliance button
        
        String name = jTextField2.getText().trim();
        
        if(name.isEmpty()){
            
            JOptionPane.showMessageDialog(this, "Please enter an appliance name.");
        }else {
            boolean deleted = manager.deleteAppliance(name);
            
            if (deleted){
                jTextArea1.setText("Appliance deleted successfully.");
                jTextField2.setText("");
            }else {
                jTextArea1.setText("Appliance not found");
            }
        }
        
    }//GEN-LAST:event_jButton2ActionPerformed

