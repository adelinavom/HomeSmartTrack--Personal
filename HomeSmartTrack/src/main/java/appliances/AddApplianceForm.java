    private Appliance createAppliance(){
        String name = jTextField1.getText().trim();
        double hoursDay = Double.parseDouble(jTextField3.getText());
        
        if (name.isEmpty()){
            throw new IllegalArgumentException("Enter an appliance name please.");
            
        }
        
        if (!Double.isFinite(hoursDay)|| hoursDay <0 || hoursDay>24){
            throw new IllegalArgumentException("Hours must be between 0 and 24. Thank you");
        }
        
        if(jRadioButton1.isSelected()){
            double watts = Double.parseDouble(jTextField2.getText());
            
        if (!Double.isFinite(watts)|| watts <=0){
            throw new IllegalArgumentException("Please enter a valid power rating. Thank you");
        }
        return new ElectricAppliances(name,hoursDay, watts);
    
    }else if (jRadioButton2.isSelected()){
        
        double gasRate = Double.parseDouble(jTextField4.getText());
        
        if (!Double.isFinite(gasRate)|| gasRate <=0){
            throw new IllegalArgumentException("Please enter a valid power rating. Thank you");
        }return new GasAppliances(name, hoursDay, gasRate);
    }else{
        throw new IllegalArgumentException("Select an appliance type please.");
    }
    }

