    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        try{
            Appliance appliance = createAppliance();
            
            if(manager.searchAppliance(appliance.getName())!= null){
                JOptionPane.showMessageDialog(this,"An Appliance with this name already exists");
            }else{
                manager.addAppliance(appliance);
                jLabel4.setText("Dailuy Energy: "+ appliance.calculateDailyEnergy() + "kWh");
                
                JOptionPane.showMessageDialog(this,"Appliance was added successfully.");
                
                jTextField1.setText("");
                jTextField2.setText("");
                jTextField3.setText("");
                jTextField4.setText("");
            }
        }catch (NumberFormatException e){
            JOptionPane.showMessageDialog(this,"Please enter valid numerical values.");
        } catch (IllegalArgumentException e){
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

